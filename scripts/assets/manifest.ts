import type { ManifestEntry } from "./types";

/**
 * Renders the typed asset manifest consumed by the app. Output is sorted and
 * stable, so re-running the sync without changes leaves the file untouched.
 */
export function renderManifest(entries: ReadonlyMap<string, ManifestEntry>): string {
  const keys = [...entries.keys()].sort();
  const body = keys
    .map((key) => {
      const entry = entries.get(key);
      return `  ${JSON.stringify(key)}: ${JSON.stringify(entry, sortedReplacer)},`;
    })
    .join("\n");

  return `// Generated by \`npm run assets:sync\` from scripts/assets/catalog.ts. Do not edit by hand.
// Every key maps to optimized objects on the asset CDN (see src/lib/asset-paths.ts).

export const assetManifest = {
${body}
} as const;

export type AssetKey = keyof typeof assetManifest;
`;
}

function sortedReplacer(_key: string, value: unknown): unknown {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return value;
  return Object.fromEntries(
    Object.entries(value as Record<string, unknown>).sort(([a], [b]) => a.localeCompare(b)),
  );
}
